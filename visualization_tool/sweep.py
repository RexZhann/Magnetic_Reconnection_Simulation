def _power_law(x, C, p):
    return C * np.asarray(x) ** p


def curve_fit(*args, **kw):
    from scipy.optimize import curve_fit as _cf   # lazy: scipy only for fits
    return _cf(*args, **kw)


def snapshot_diagnostics(df, output_dir):
    """Physics diagnostics from the final snapshot of every surviving run."""
    import pandas as pd
    rows = []
    for _, r in df[df["survived"]].iterrows():
        snap = load_final(os.path.join(output_dir, r["label"]))
        if snap is None or snap["nx"] != int(r["nx"]) or snap["ny"] != int(r["ny"]):
            continue
        rows.append({
            "nx": int(r["nx"]), "ny": int(r["ny"]), "dx": r["dx"], "eta_H": r["eta_H"],
            "t_snap": snap["t"],
            "rec_rate_proxy": physics.midplane_flux_max(snap),
            "cs_width": physics.current_sheet_width(snap),
            "max_jz": physics.max_abs_jz_periodic(snap),
            "quad_bz": physics.quadrupole_bz(snap),
            "min_rho_snap": float(np.min(snap["rho"])),
        })
    return pd.DataFrame(rows)


def plot_survival_map(df, save_path=None):
    grids = sorted(df.groupby(["nx", "ny"]).groups.keys())
    fig, axes = plt.subplots(1, len(grids), figsize=(5 * len(grids), 4), squeeze=False)
    for ax, (nx, ny) in zip(axes[0], grids):
        sub = df[(df["nx"] == nx) & (df["ny"] == ny)].sort_values("eta_H", ascending=False)
        surv = sub["survived"].values.astype(bool)
        y = range(len(sub))
        ax.barh(list(y), [1] * len(sub), color=["#2ecc71" if s else "#e74c3c" for s in surv],
                edgecolor="k", linewidth=0.5)
        ax.set_yticks(list(y))
        ax.set_yticklabels([f"{e:.2e}" for e in sub["eta_H"]], fontsize=8)
        ax.set_xticks([]); ax.set_title(f"{nx}x{ny}")
        if (nx, ny) == grids[0]:
            ax.set_ylabel(r"$\eta_H$")
        for i, (s, tf) in enumerate(zip(surv, sub["t_final"].values)):
            ax.text(0.5, i, "ok" if s else f"crash t={tf:.1f}", ha="center", va="center",
                    fontsize=7, color="white", fontweight="bold")
    fig.legend(handles=[Patch(facecolor="#2ecc71", label="survived"),
                        Patch(facecolor="#e74c3c", label="crashed")],
               loc="upper right", fontsize=9)
    fig.suptitle(r"$\eta_H$ stability sweep: survival map", fontsize=13, fontweight="bold")
    fig.tight_layout()
    return save(fig, save_path)


def plot_overdamp_curves(diag, save_path=None):
    if diag.empty:
        print("  no diagnostics, skipping over-damping figure")
        return None
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 4))
    for k, nx in enumerate(sorted(diag["nx"].unique())):
        sub = diag[diag["nx"] == nx].sort_values("eta_H")
        lbl = f"{nx}x{sub['ny'].iloc[0]}"
        ax1.plot(sub["eta_H"], sub["max_jz"], f"C{k}", marker="os^dv"[k % 5], label=lbl)
        ax2.plot(sub["eta_H"], sub["quad_bz"], f"C{k}", marker="os^dv"[k % 5], label=lbl)
    for ax, yl, ttl in ((ax1, r"max $|J_z|$", "peak current (lowered by over-damping)"),
                        (ax2, r"$|B_z|_{\rm quad}$", r"Hall quadrupole (erased at large $\eta_H$)")):
        ax.set_xscale("log"); ax.set_xlabel(r"$\eta_H$"); ax.set_ylabel(yl)
        ax.set_title(ttl, fontsize=10); ax.legend(); ax.grid(True, which="both", alpha=0.3)
    fig.suptitle("Over-damping cost (surviving runs)", fontsize=12, fontweight="bold")
    fig.tight_layout()
    return save(fig, save_path)


def plot_scaling_law(eta_min: dict, save_path=None):
    """log-log eta_H^min vs dx with power-law fit and the dx^2/pi^2 anchor."""
    items = sorted((dx, em) for (_, _, dx), em in eta_min.items() if not math.isnan(em))
    if len(items) < 2:
        print("  fewer than 2 points, skipping scaling-law figure")
        return None
    dxs, ems = map(np.array, zip(*items))
    fig, ax = plt.subplots(figsize=(6, 5))
    ax.loglog(dxs, ems, "ko", ms=8, label=r"measured $\eta_H^{\min}$")
    dxf = np.logspace(np.log10(dxs.min() * 0.8), np.log10(dxs.max() * 1.2), 50)
    try:
        (C, p), _ = curve_fit(_power_law, dxs, ems, p0=[1.0, 2.0])
        ax.loglog(dxf, _power_law(dxf, C, p), "r--",
                  label=rf"fit $\eta_H^{{\min}}={C:.4f}\,\Delta x^{{{p:.3f}}}$")
    except Exception as e:                       # noqa: BLE001
        print(f"  fit failed: {e}")
    ax.loglog(dxf, dxf ** 2 / math.pi ** 2, "b:", alpha=0.6,
              label=r"reference $\Delta x^2/\pi^2$")
    ax.set_xlabel(r"$\Delta x$"); ax.set_ylabel(r"$\eta_H^{\min}$ (stability bound)")
    ax.set_title(r"$\eta_H^{\min} \propto \Delta x^p$", fontsize=13, fontweight="bold")
    ax.legend(fontsize=10); ax.grid(True, which="both", alpha=0.3)
    fig.tight_layout()
    return save(fig, save_path)


def analyze_sweep(output_dir="output/eta_H_sweep", csv_path=None):
    """Diagnostics CSV, scaling-law report and three figures into ``output_dir``."""
    import pandas as pd
    csv_path = csv_path or os.path.join(output_dir, "sweep_results.csv")
    df = pd.read_csv(csv_path)
    print(f"{len(df)} runs, {int(df['survived'].sum())} survived")

    diag = snapshot_diagnostics(df, output_dir)
    if not diag.empty:
        diag.to_csv(os.path.join(output_dir, "diagnostics.csv"), index=False)

    eta_min, lines = {}, []
    for (nx, ny), g in df.groupby(["nx", "ny"]):
        dx = float(g["dx"].iloc[0])
        anchor = dx ** 2 / math.pi ** 2
        surv = g[g["survived"]]["eta_H"]
        em = float(surv.min()) if not surv.empty else float("nan")
        eta_min[(nx, ny, dx)] = em
        crash_t = g[~g["survived"]]["t_final"].min() if not surv.empty else float("nan")
        lines.append(f"  {nx}x{ny}  dx={dx:.4f}  anchor={anchor:.3e}  eta_H^min={em:.3e}  "
                     f"ratio={em / anchor:.3f}  first crash t~{crash_t:.1f}")
    report = "=== eta_H^min vs dx scaling fit ===\n\n" + "\n".join(lines) + "\n\n"
    pts = sorted((dx, em) for (_, _, dx), em in eta_min.items() if not math.isnan(em) and em > 0)
    if len(pts) >= 2:
        dxs, ems = map(np.array, zip(*pts))
        try:
            (C, p), pcov = curve_fit(_power_law, dxs, ems, p0=[1.0, 2.0])
            perr = np.sqrt(np.diag(pcov))
            report += (f"fit: eta_H^min = C * dx^p\n  C = {C:.6f} +/- {perr[0]:.6f}\n"
                       f"  p = {p:.4f} +/- {perr[1]:.4f}\n\n"
                       f"  expected: p ~ 2, C ~ 1/pi^2 = {1/math.pi**2:.4f}\n")
        except Exception as e:                   # noqa: BLE001
            report += f"fit failed: {e}\n"
    else:
        report += "fewer than 2 points, no fit\n"
    with open(os.path.join(output_dir, "scaling_fit.txt"), "w", encoding="utf-8") as f:
        f.write(report)
    print(report)

    plot_survival_map(df, os.path.join(output_dir, "fig1_survival_map.png"))
    plot_overdamp_curves(diag, os.path.join(output_dir, "fig2_overdamp_curves.png"))
    plot_scaling_law(eta_min, os.path.join(output_dir, "fig3_scaling_law.png"))
