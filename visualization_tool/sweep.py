# (nx, ny, t_end); 256x128 shortened to t=8 to save time
DEFAULT_GRIDS = [(64, 32, 15.0), (128, 64, 15.0), (256, 128, 8.0)]
# eta_H sequence per grid, large -> small (stops after two consecutive crashes)
DEFAULT_ETA_H = {
    (64, 32):   [3.2e-2, 1.6e-2, 8e-3, 4e-3, 2e-3, 1e-3, 5e-4, 2.5e-4, 1e-4, 5e-5],
    (128, 64):  [8e-3, 4e-3, 2e-3, 1e-3, 5e-4, 3e-4, 1.5e-4, 7.5e-5, 3e-5, 1e-5],
    (256, 128): [2e-3, 1e-3, 5e-4, 2.5e-4, 1e-4, 5e-5, 2.5e-5, 1e-5],
}
LX_HARRIS = 4 * math.pi          # harris_sheet.hpp: Lx = 4 pi, Ly = 2 pi
FIELDS = ["nx", "ny", "dx", "eta_H", "anchor_etaH", "t_end", "survived", "t_final",
          "t_crash", "min_rho_last", "max_v_last", "N_sub_last", "crash_reason",
          "wall_s", "exit_code", "label"]
_NUM = r"[-+]?[0-9]*\.?[0-9]+(?:[eE][-+]?[0-9]+)?"


def parse_stdout(stdout: str, t_end: float) -> dict:
    """Survival / crash information from mhd2d stdout."""
    r = {"survived": False, "t_crash": -1.0, "t_final": 0.0,
         "min_rho_last": float("nan"), "N_sub_last": -1,
         "max_v_last": float("nan"), "crash_reason": ""}
    m = re.search(r"Finished:\s+\d+\s+steps,\s+t=([0-9.e+\-]+)", stdout)
    if m:
        r["t_final"] = float(m.group(1))
        r["survived"] = r["t_final"] >= t_end - 1e-3
    if re.search(r"\*\*\* FATAL", stdout):
        r["crash_reason"] = "FATAL_unphysical"
    steps = re.findall(rf"Step\s+\d+\s+t=({_NUM})\s+dt={_NUM}\s+min_rho=({_NUM})\s+"
                       rf".*?max\|v\|=({_NUM})(?:.*?N_sub=(\d+))?", stdout)
    if steps:
        last = steps[-1]
        r["t_crash"], r["min_rho_last"] = float(last[0]), float(last[1])
        r["max_v_last"] = float(last[2])
        r["N_sub_last"] = int(last[3]) if last[3] else -1
    if not r["survived"] and not r["crash_reason"] and r["t_final"] < t_end - 0.5:
        r["crash_reason"] = "early_exit"
    if (not r["survived"] and not math.isnan(r["min_rho_last"])
            and r["min_rho_last"] <= 0.021 and not r["crash_reason"]):
        r["crash_reason"] = "floor_hit"
    return r


def run_one(nx, ny, eta_H, t_end, output_dir, binary=None, test=21) -> dict:
    """One sweep point: write a ctrl deck into the run folder and run it."""
    binary = binary or os.path.join(repo_root(), "build", "mhd2d")
    label = f"sweep_etaH{eta_H:.3e}_{nx}x{ny}"
    run_dir = os.path.join(output_dir, label)
    os.makedirs(run_dir, exist_ok=True)
    deck = os.path.join(run_dir, "ctrl_sweep.txt")
    with open(deck, "w") as f:
        f.write(f"! generated by visualization_tool.sweep\n test = {test}\n"
                f" nx = {nx}\n ny = {ny}\n divb = 'CT'\n solver = 'HLLD'\n"
                f" eta_H = {eta_H:.6e}\n t_stop = {t_end:.4f}\n"
                f" output_dir = '{os.path.abspath(output_dir)}'\n label = '{label}'\n")
    print(f"  run: {label}", flush=True)
    t0 = time.time()
    proc = subprocess.run([binary, deck], capture_output=True, text=True,
                          encoding="utf-8", errors="replace", cwd=repo_root())
    wall = time.time() - t0
    r = parse_stdout(proc.stdout + proc.stderr, t_end)
    r.update(label=label, nx=nx, ny=ny, eta_H=eta_H, t_end=t_end,
             wall_s=round(wall, 1), exit_code=proc.returncode)
    with open(os.path.join(run_dir, "run.log"), "w", encoding="utf-8") as f:
        f.write("=== STDOUT ===\n" + proc.stdout + "\n=== STDERR ===\n" + proc.stderr)
    status = "survived" if r["survived"] else f"crashed ({r['crash_reason']})"
    print(f"    -> {status}, t_final={r['t_final']:.3f}, min_rho={r['min_rho_last']:.4f}, "
          f"N_sub={r['N_sub_last']}, {wall:.0f}s", flush=True)
    return r


def run_sweep(output_dir="output/eta_H_sweep", grids=DEFAULT_GRIDS,
              eta_seq=DEFAULT_ETA_H, binary=None, csv_path=None) -> str:
    """Run the whole sweep; returns the results CSV path (rewritten after each grid)."""
    os.makedirs(output_dir, exist_ok=True)
    csv_path = csv_path or os.path.join(output_dir, "sweep_results.csv")
    rows = []
    for nx, ny, t_end in grids:
        dx = LX_HARRIS / nx
        anchor = dx * dx / math.pi ** 2          # eta_H^crit = dx^2/pi^2
        print(f"\n=== {nx}x{ny}  dx={dx:.4f}  anchor eta_H={anchor:.3e}  t_end={t_end}")
        crashes = 0
        for eta_H in eta_seq.get((nx, ny), []):
            r = run_one(nx, ny, eta_H, t_end, output_dir, binary)
            r.update(dx=dx, anchor_etaH=anchor)
            rows.append(r)
            crashes = 0 if r["survived"] else crashes + 1
            if crashes >= 2:
                print(f"  two consecutive crashes, stopping {nx}x{ny}")
                break
        with open(csv_path, "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=FIELDS, extrasaction="ignore")
            w.writeheader()
            w.writerows(rows)
        print(f"  updated {csv_path}")
    return csv_path


