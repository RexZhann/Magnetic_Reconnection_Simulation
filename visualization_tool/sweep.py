"""eta_H stability sweep for the Hall-MHD Harris sheet (test 21).

Former output/eta_H_sweep/run_sweep.py + analyze.py. ``run_sweep`` drives
build/mhd2d through generated ctrl decks; ``analyze_sweep`` reads the results
CSV + final snapshots and writes the three figures and the scaling-law fit.
"""

